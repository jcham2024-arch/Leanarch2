// Helper to parse raw error messages cleanly
function formatErrorMessage(err: any): string {
  if (!err) return 'Unknown server error';
  let msg = typeof err === 'string' ? err : err.message || String(err);
  try {
    const parsed = JSON.parse(msg);
    if (parsed.error?.message) {
      msg = parsed.error.message;
    }
  } catch {
    // Not JSON
  }
  return msg;
}

// Helper to check if error is 429 / Rate Limit / Quota Exceeded
function isQuotaError(err: any): boolean {
  const msg = formatErrorMessage(err).toLowerCase();
  return msg.includes('429') || msg.includes('resource_exhausted') || msg.includes('quota') || msg.includes('rate limit');
}

